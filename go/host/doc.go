// Package host 实现桌面外壳的宿主管理层。
//
// “宿主”指承载网页的 Go/Wails 桌面进程。网页负责业务界面，本包负责它所使用的桌面能力：
//
//   - controller.go：登记和复用窗口、跟踪页面加载、检查未完成任务、处理唤醒及退出。
//   - policy.go：校验调用来源和能力，并限制子窗口不能超过创建者的权限上限。
//   - state.go：保存窗口位置、尺寸和最大化状态，在显示器变化后把窗口调整到可见区域。
//   - errors.go：提供前端能识别的统一错误码和中文说明。
//   - commands*.go、cache.go、eventbus.go：管理受权限约束的命令、共享内存缓存和按来源路由的业务事件。
//   - desktop.go、downloads.go：管理文件授权凭证、界面偏好和受退出保护的后台下载。
//   - integration.go、native_*.go：提供通知、快捷键、入口路由、设置及按平台实现的系统凭据和剪贴板。
//
// 本包不直接作为前端服务暴露。go/services 中的服务先检查调用权限，再委托本包执行管理操作；
// main.go 则负责把本包与 Wails 应用连接起来，并配置单实例锁和应用启动参数。
